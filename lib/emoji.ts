/** 전체 이모지 개수 */
export const EMOJI_COUNT = EMOJI_GROUPS.reduce((n, g) => n + g.items.length, 0);

/**
 * 한글 검색 — 공백으로 나눈 단어가 **모두** 키워드나 분류명에 들어가면 결과.
 * (검색어가 비면 전체를 분류 그대로 돌려준다)
 */
export function searchEmoji(q: string): EmojiGroup[] {
  const words = q.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (words.length === 0) return EMOJI_GROUPS;
  const hits: EmojiGroup['items'] = [];
  for (const g of EMOJI_GROUPS) {
    for (const item of g.items) {
      const hay = `${item[1]} ${g.name}`.toLowerCase();
      if (words.every((w) => hay.includes(w))) hits.push(item);
    }
  }
  return hits.length > 0 ? [{ name: `검색 결과 ${hits.length}개`, items: hits }] : [];
}
